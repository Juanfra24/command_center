import 'package:equatable/equatable.dart';

class Skills extends Equatable {
  final int attack,
      defence,
      strength,
      hitpoints,
      range,
      prayer,
      magic,
      cooking,
      woodcutting,
      fletching,
      fishing,
      firemaking,
      crafting,
      mining,
      smithing,
      agility,
      herblore,
      thieving,
      slayer,
      farming,
      runecrafting,
      construction,
      hunter;

  const Skills({
    required this.attack,
    required this.defence,
    required this.strength,
    required this.hitpoints,
    required this.range,
    required this.prayer,
    required this.magic,
    required this.cooking,
    required this.woodcutting,
    required this.fletching,
    required this.fishing,
    required this.firemaking,
    required this.crafting,
    required this.mining,
    required this.smithing,
    required this.agility,
    required this.herblore,
    required this.thieving,
    required this.slayer,
    required this.farming,
    required this.runecrafting,
    required this.construction,
    required this.hunter,
  });

  factory Skills.fromJson(Map<String, dynamic>? json) {
    if (json == null) {
      return Skills.defaultSkills();
    }
    return Skills(
      attack: json['Attack'] ?? 0,
      defence: json['Defence'] ?? 0,
      strength: json['Strength'] ?? 0,
      hitpoints: json['Hitpoints'] ?? 0,
      range: json['Range'] ?? 0,
      prayer: json['Prayer'] ?? 0,
      magic: json['Magic'] ?? 0,
      cooking: json['Cooking'] ?? 0,
      woodcutting: json['Woodcutting'] ?? 0,
      fletching: json['Fletching'] ?? 0,
      fishing: json['Fishing'] ?? 0,
      firemaking: json['Firemaking'] ?? 0,
      crafting: json['Crafting'] ?? 0,
      mining: json['Mining'] ?? 0,
      smithing: json['Smithing'] ?? 0,
      agility: json['Agility'] ?? 0,
      herblore: json['Herblore'] ?? 0,
      thieving: json['Thieving'] ?? 0,
      slayer: json['Slayer'] ?? 0,
      farming: json['Farming'] ?? 0,
      runecrafting: json['Runecrafting'] ?? 0,
      construction: json['Construction'] ?? 0,
      hunter: json['Hunter'] ?? 0,
    );
  }

  static Skills defaultSkills() {
    return const Skills(
      attack: 0,
      defence: 0,
      strength: 0,
      hitpoints: 0,
      range: 0,
      prayer: 0,
      magic: 0,
      cooking: 0,
      woodcutting: 0,
      fletching: 0,
      fishing: 0,
      firemaking: 0,
      crafting: 0,
      mining: 0,
      smithing: 0,
      agility: 0,
      herblore: 0,
      thieving: 0,
      slayer: 0,
      farming: 0,
      runecrafting: 0,
      construction: 0,
      hunter: 0,
    );
  }

  @override
  List<Object?> get props => [
        attack,
        defence,
        strength,
        hitpoints,
        range,
        prayer,
        magic,
        cooking,
        woodcutting,
        fletching,
        fishing,
        firemaking,
        crafting,
        mining,
        smithing,
        agility,
        herblore,
        thieving,
        slayer,
        farming,
        runecrafting,
        construction,
        hunter
      ];
}
